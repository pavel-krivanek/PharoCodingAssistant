#!/usr/bin/env sh
set -eu
if [ "$#" -lt 10 ]; then
    echo "usage: $0 VM IMAGE REPOSITORY EVALUATION_REPOSITORY TASK WORKER_RESULT EVALUATION TIMEOUT_SECONDS STDOUT STDERR" >&2
    exit 2
fi
VM=$1
IMAGE=$2
REPOSITORY=$3
EVALUATION_REPOSITORY=$4
TASK=$5
WORKER_RESULT=$6
EVALUATION=$7
TIMEOUT_SECONDS=$8
STDOUT=$9
shift 9
STDERR=$1
SCRIPT="$REPOSITORY/scripts/run-benchmark-evaluator.st"
export PCA_BENCH_REPOSITORY="$REPOSITORY"
export PCA_BENCH_EVALUATION_REPOSITORY="$EVALUATION_REPOSITORY"
export PCA_BENCH_TASK="$TASK"
export PCA_BENCH_WORKER_RESULT="$WORKER_RESULT"
export PCA_BENCH_EVALUATION_OUTPUT="$EVALUATION"
if command -v timeout >/dev/null 2>&1; then
    timeout "${TIMEOUT_SECONDS}s" "$VM" --headless "$IMAGE" st --quit "$SCRIPT" >"$STDOUT" 2>"$STDERR"
else
    "$VM" --headless "$IMAGE" st --quit "$SCRIPT" >"$STDOUT" 2>"$STDERR"
fi
