    [System.IO.File]::WriteAllText($probeScript, $probe, [System.Text.UTF8Encoding]::new($false))

    Remove-Item -LiteralPath $marker -Force -ErrorAction SilentlyContinue
    $stdout = Join-Path $StateDirectory 'pharo-preflight.stdout.log'
    $stderr = Join-Path $StateDirectory 'pharo-preflight.stderr.log'
    Write-Step 'Testing explicit headless Pharo command-line execution'
    $result = Invoke-PharoProcess -Vm $Vm -Image $Image -Script $probeScript -Stdout $stdout -Stderr $stderr -TimeoutSeconds 60
    if ($result.ExitCode -eq 0 -and (Test-Path -LiteralPath $marker -PathType Leaf)) {
        Write-Info 'Pharo .st execution works in explicit --headless mode.'
        [System.IO.File]::WriteAllText($PharoInvocationRecordFile, 'headless', [System.Text.UTF8Encoding]::new($false))
        return 'headless'
    }

    Show-ProcessDiagnostics -Stdout $stdout -Stderr $stderr
    throw "The extracted Pharo VM did not execute a .st file with explicit --headless. See $StateDirectory\pharo-preflight*.log"
}

function Get-ApiUrls {
    $root = $LmStudioUrl.TrimEnd('/')
    if ($root -match '/v1$') {
        $serverRoot = $root.Substring(0, $root.Length - 3).TrimEnd('/')
        $v1 = $root
    } else {
        $serverRoot = $root
        $v1 = "$root/v1"
    }
    return [pscustomobject]@{
        ServerRoot = $serverRoot
        V1 = $v1
        Models = "$v1/models"
        NativeModels = "$serverRoot/api/v1/models"
        Chat = "$v1/chat/completions"
    }
}


function Get-OptionalPropertyValue {
    param(
        [AllowNull()]
        [object]$Object,

        [Parameter(Mandatory = $true)]
        [string]$Name
    )

    if ($null -eq $Object) {
        return $null
    }

    $property = $Object.PSObject.Properties[$Name]
    if ($null -eq $property) {
        return $null
    }

    return $property.Value
}


