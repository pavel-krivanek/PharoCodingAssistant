    $urls = Get-ApiUrls
    Ensure-Directory $ProfileDirectory

    $reasoningOptions = @($Metadata.ReasoningOptions | ForEach-Object { [string]$_ })
    $reasoningEffort = if ($null -eq $Metadata.EffectiveReasoning) { $null } else { [string]$Metadata.EffectiveReasoning }

    $profile = [ordered]@{
        format = 'PharoCodingAssistantRuntimeProfile'
        version = 1
        savedAt = (Get-Date).ToString('o')
        profile = [ordered]@{
            providers = @(
                [ordered]@{
                    family = 'openai-compatible'
                    baseUrl = $urls.Chat
                    modelListUrl = $urls.Models
                    credentialName = 'lmstudio-api-key'
                    timeout = 3600
                    serverTelemetryMode = 'auto'
                    modelDiscovery = $true
                    id = $ProviderId
                }
            )
            models = @(
                [ordered]@{
                    modelId = $SelectedModelId
                    providerId = $ProviderId
                    contextSize = [int64]$Metadata.ContextSize
                    maximumContextSize = $Metadata.MaximumContextSize
                    contextSizeSource = [string]$Metadata.ContextSizeSource
                    maximumOutputTokens = $MaximumOutputTokens
                    reasoningEfforts = $reasoningOptions
                    defaultReasoningEffort = $Metadata.DefaultReasoning
                    metadataSource = $Metadata.MetadataSource
                    capabilities = [ordered]@{
                        tools = [bool]$Metadata.SupportsTools
                        parallelToolCalls = $false
                        reasoning = [bool]$Metadata.SupportsReasoning
                        reasoningStreaming = [bool]$Metadata.SupportsReasoning
                        usageStreaming = $false
                        images = [bool]$Metadata.SupportsImages
                        systemMessages = $true
                    }
                }
            )
            agents = @(
                [ordered]@{
                    agentId = 'default'
