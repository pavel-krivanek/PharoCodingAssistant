<#
.SYNOPSIS
    One-command Windows launcher for the PharoCodingAssistant benchmark.

.DESCRIPTION
    Expected stable inputs below the script directory (default C:\tmp\benchmark):

      resources\pharo-vm-Windows-x86_64-latest.zip
      resources\pharoImage-x86_64.zip
      (hidden evaluations live in a separate repository; default C:\repos\PharoCodingAssistant-BenchmarkEvaluations)
      run-pca-benchmark.ps1

    PCA itself is read from C:\repos\PharoCodingAssistant by default. Hidden evaluator/solution classes are read only by post-worker evaluator processes from C:\repos\PharoCodingAssistant-BenchmarkEvaluations by default.
    Everything generated by this script is placed below work\ and can be removed with -Mode Clean.

    LM Studio must already be running and the intended model must be available through its
    OpenAI-compatible API. Context size and model-specific reasoning modes are auto-detected
    from LM Studio native /api/v1/models metadata when available. The script creates an isolated
    PCA runtime.json itself; it does not
    read ~/.pharo-ca and therefore does not inherit personal PCA instructions/sessions/settings.

.EXAMPLE
    .\run-pca-benchmark.ps1 -Mode Prepare

.EXAMPLE
    .\run-pca-benchmark.ps1 -Mode Smoke -Verbosity 2

.EXAMPLE
    .\run-pca-benchmark.ps1 -Mode Smoke -ModelId ornith-1.5-35b-a3b -Reasoning provider-default

.EXAMPLE
    .\run-pca-benchmark.ps1 -Mode Full -ModelId qwen3.8-27b -Reasoning high

.EXAMPLE
    .\run-pca-benchmark.ps1 -Mode Quick -SkillModes both

.EXAMPLE
    .\run-pca-benchmark.ps1 -Mode Task -Tasks 'navigation-007-cache-invalidation' -SkillModes normal

.EXAMPLE
    .\run-pca-benchmark.ps1 -Mode Full -SkillModes both -TimeoutSeconds 1800 -Verbosity 3

.EXAMPLE
    .\run-pca-benchmark.ps1 -Mode Full -Repeat 3 -PruneRunImages:$true

.EXAMPLE
    .\run-pca-benchmark.ps1 -Mode Models

.EXAMPLE
    .\run-pca-benchmark.ps1 -Mode Status

.EXAMPLE
    .\run-pca-benchmark.ps1 -Mode Clean
#>
[CmdletBinding()]
param(
    [ValidateSet('Prepare','Smoke','Quick','Full','Task','Status','Models','Clean')]
    [string]$Mode = 'Smoke',

    # Leave empty to auto-detect the directory containing this script.
    # Using $PSScriptRoot directly as a parameter default is unreliable in Windows PowerShell 5.1.
    [string]$BaseDirectory = '',
    [string]$Repository = 'C:\repos\PharoCodingAssistant',
    [string]$EvaluationRepository = 'C:\repos\PharoCodingAssistant-BenchmarkEvaluations',

    # LM Studio OpenAI-compatible API root. Both http://host:port and .../v1 are accepted.
    [string]$LmStudioUrl = 'http://127.0.0.1:1234',
    [string]$ProviderId = 'lmstudio',
    [string]$ModelId = '',
    [string]$ModelPattern = '*qwen3.8*27b*',

    # 0 = auto-detect the effective loaded context from LM Studio /api/v1/models.
    # A positive value is an explicit override.
    [int64]$ContextSize = 0,
    [int]$MaximumOutputTokens = 16384,

    # provider-default omits reasoning_effort and lets the model/provider choose its advertised default.
    # Otherwise use one of the options reported by LM Studio for the selected model.
    [Alias('ReasoningEffort')]
    [string]$Reasoning = 'provider-default',

    [ValidateSet('normal','preloaded','both')]
    [string]$SkillModes = 'both',

    # 0=silent agent progress, 1=task lifecycle, 2=model/tool activity, 3=live generated model output/reasoning.
    [ValidateRange(0,3)]
    [int]$Verbosity = 1,

    [string]$Tasks = '',
    [int]$Repeat = 1,

    # Local models can legitimately take a long time on navigation tasks.
    [int]$TimeoutSeconds = 1800,
    [int]$EvaluatorTimeoutSeconds = 180,

    [switch]$Fresh,
    [switch]$NoEvaluation,
    [switch]$SkipLmStudioCheck,
    [bool]$PruneRunImages = $true
)

