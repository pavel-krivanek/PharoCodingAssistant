        }
    }

    $json = $profile | ConvertTo-Json -Depth 20
    [System.IO.File]::WriteAllText($RuntimeProfileFile, $json, [System.Text.UTF8Encoding]::new($false))
}

function Get-GitCommit {
    if ($null -eq (Get-Command git -ErrorAction SilentlyContinue)) { return $null }
    try {
        $commit = (& git -C $Repository rev-parse HEAD 2>$null)
        if ($LASTEXITCODE -eq 0) { return ($commit | Select-Object -First 1) }
    } catch { }
    return $null
}

