function Prepare-Benchmark {
    Assert-Inputs

    if ($Fresh) { Remove-GeneratedWork }

    Ensure-Directory $WorkDirectory
    Ensure-Directory $RunsDirectory
    Ensure-Directory $ResultsDirectory
    Ensure-Directory $StateDirectory

    Expand-ArchiveOnce -Archive $VmArchive -Destination $VmDirectory -MarkerName '.extracted-ok'
    Expand-ArchiveOnce -Archive $ImageArchive -Destination $ImageDirectory -MarkerName '.extracted-ok'

    $vm = Find-PharoVm
    $image = Find-PharoImage
    $invocationStyle = Test-PharoCommandLine -Vm $vm -Image $image

    $selectedModel = $null
    $models = @()
    $nativeModels = @()
    if ($SkipLmStudioCheck) {
        if ([string]::IsNullOrWhiteSpace($ModelId)) {
            throw '-SkipLmStudioCheck requires -ModelId because the script cannot discover a model identifier.'
        }
        if ($ContextSize -le 0) {
            throw '-SkipLmStudioCheck also requires an explicit -ContextSize because context auto-detection is disabled.'
        }
        if ($Reasoning.Trim().ToLowerInvariant() -notin @('provider-default','auto')) {
            throw '-SkipLmStudioCheck cannot validate a reasoning level. Use -Reasoning provider-default or enable the LM Studio check.'
        }
        $selectedModel = $ModelId
        $metadata = [pscustomobject]@{
            ContextSize = [int64]$ContextSize
            MaximumContextSize = $null
            ContextSizeSource = 'manual-override'
            MetadataSource = 'manual'
            ReasoningOptions = @()
            DefaultReasoning = $null
            RequestedReasoning = 'provider-default'
            EffectiveReasoning = $null
            SupportsReasoning = $false
            SupportsTools = $true
            SupportsImages = $false
        }
    } else {
        $models = @(Get-LmStudioModels)
        $selectedModel = Select-LmStudioModel $models
        $nativeModels = @(Get-LmStudioNativeModels)
        $metadata = Resolve-LmStudioModelMetadata -OpenAiModels $models -NativeModels $nativeModels -SelectedModelId $selectedModel
    }

    Write-Step 'Writing isolated PCA benchmark profile'
    Write-RuntimeProfile -SelectedModelId $selectedModel -Metadata $metadata
    Write-EnvironmentRecord -Vm $vm -Image $image -SelectedModelId $selectedModel -Metadata $metadata

    Write-Info "VM:      $vm"
    Write-Info "Image:   $image"
    Write-Info "Model:   $selectedModel"
    Write-Info "Context: $($metadata.ContextSize) ($($metadata.ContextSizeSource))"
    if ($null -ne $metadata.MaximumContextSize) { Write-Info "Max context: $($metadata.MaximumContextSize)" }
    $reasoningText = if ($metadata.ReasoningOptions.Count -eq 0) { 'not advertised' } else { ($metadata.ReasoningOptions -join '/') + ' (default=' + $metadata.DefaultReasoning + ')' }
    Write-Info "Reasoning: $reasoningText"
    Write-Info "Selected reasoning: $($metadata.RequestedReasoning)"
    Write-Info "Profile: $ProfileDirectory"
    if (-not $NoEvaluation) { Write-Info "Evaluations: $EvaluationRepository" }

    return [pscustomobject]@{
        Vm = $vm
        Image = $image
        ModelId = $selectedModel
        InvocationStyle = $invocationStyle
    }
}

function Prune-RunImages {
    if (-not $PruneRunImages) { return }
    if (-not (Test-Path -LiteralPath $RunsDirectory)) { return }

    Write-Step 'Pruning disposable worker/evaluator images from completed runs'
    $images = @(Get-ChildItem -LiteralPath $RunsDirectory -Recurse -File -Filter '*.image' -ErrorAction SilentlyContinue)
    $count = 0
    $bytes = [int64]0
    foreach ($file in $images) {
        $bytes += $file.Length
        Remove-Item -LiteralPath $file.FullName -Force
        $count++
    }
    $mb = [Math]::Round($bytes / 1MB, 1)
    Write-Info "Removed $count disposable image(s), $mb MB. Logs/results/workspaces remain."
}

function Show-SuiteSummary([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        throw "Suite result does not exist: $Path"
    }
    $summary = Get-Content -LiteralPath $Path -Raw | ConvertFrom-Json

    Write-Host ''
    Write-Host "Suite: $Path" -ForegroundColor Green
    Write-Host "Task set: $($summary.taskSetVersion)   requested tasks: $($summary.requestedTaskCount)   runs: $($summary.runCount)"
    Write-Host "Duration: $([Math]::Round(([double]$summary.durationMilliseconds / 60000.0), 1)) min"
    foreach ($mode in @($summary.modeSummaries)) {
        $avg = if ($null -eq $mode.averageScore) { 'n/a' } else { '{0:P1}' -f [double]$mode.averageScore }
        Write-Host ("  {0,-10} avg {1,7}   pass {2,3}  partial {3,3}  fail {4,3}  scored {5,3}/{6,3}" -f `
            $mode.mode, $avg, $mode.passed, $mode.partial, $mode.failed, $mode.scoredCount, $mode.runCount)
    }
    if ($null -ne $summary.skillDelta -and $summary.skillDelta.pairedTaskCount -gt 0) {
        $delta = '{0:+0.000;-0.000;0.000}' -f [double]$summary.skillDelta.averageDelta
        Write-Host "  skill delta: $delta across $($summary.skillDelta.pairedTaskCount) paired task(s)"
    }

    $problemRuns = @($summary.runs | Where-Object {
        $_.status -ne 'completed' -or ($null -ne $_.outcome -and $_.outcome -ne 'passed')
    })
    if ($problemRuns.Count -gt 0) {
        Write-Host ''
        Write-Host 'Non-passing / infrastructure runs:' -ForegroundColor Yellow
        foreach ($run in $problemRuns) {
            Write-Host "  $($run.taskId) [$($run.skillMode)] status=$($run.status) outcome=$($run.outcome) score=$($run.score)"
        }
    }
}

function Get-LatestSuiteResult {
    if (-not (Test-Path -LiteralPath $ResultsDirectory)) { return $null }
    return Get-ChildItem -LiteralPath $ResultsDirectory -File -Filter 'suite-*.json' |
        Sort-Object -Property LastWriteTimeUtc -Descending |
        Select-Object -First 1
}

function Invoke-BenchmarkSuite([string]$TaskList, [string]$Label) {
    $prepared = Prepare-Benchmark
    Ensure-Directory $ResultsDirectory

    for ($i = 1; $i -le $Repeat; $i++) {
        $timestamp = Get-Date -Format 'yyyyMMdd-HHmmss'
        $safeLabel = ($Label -replace '[^A-Za-z0-9_-]', '-')
        $output = Join-Path $ResultsDirectory "suite-$timestamp-$safeLabel-r$i.json"

        Write-Step "Running benchmark ($Label), repetition $i/$Repeat"
        Write-Info "Model: $($prepared.ModelId)"
        Write-Info "Skill modes: $SkillModes"
        Write-Info "Timeout: $TimeoutSeconds s/task"
        if ([string]::IsNullOrWhiteSpace($TaskList)) {
            Write-Info 'Tasks: full catalog'
        } else {
            Write-Info "Tasks: $TaskList"
        }

        $effectiveSkillModes = if ($SkillModes -eq 'both') { 'normal,preloaded' } else { $SkillModes }
        $suiteEnvironment = @{
            'PCA_BENCH_REPOSITORY' = $Repository
            'PCA_BENCH_VM' = $prepared.Vm
            'PCA_BENCH_BASE_IMAGE' = $prepared.Image
            'PCA_BENCH_PROFILE_ROOT' = $ProfileDirectory
            'PCA_BENCH_RUNS' = $RunsDirectory
            'PCA_BENCH_SKILL_MODES' = $effectiveSkillModes
            'PCA_BENCH_TASKS' = $TaskList
            'PCA_BENCH_TIMEOUT' = [string]$TimeoutSeconds
            'PCA_BENCH_EVALUATOR_TIMEOUT' = [string]$EvaluatorTimeoutSeconds
            'PCA_BENCH_SUITE_OUTPUT' = $output
            'PCA_BENCH_VERBOSITY' = [string]$Verbosity
        }
        if ($NoEvaluation) {
            $suiteEnvironment['PCA_BENCH_EVALUATION_REPOSITORY'] = $null
        } else {
            $suiteEnvironment['PCA_BENCH_EVALUATION_REPOSITORY'] = $EvaluationRepository
        }

        $suiteStdout = Join-Path $ResultsDirectory "suite-$timestamp-$safeLabel-r$i.stdout.log"
        $suiteStderr = Join-Path $ResultsDirectory "suite-$timestamp-$safeLabel-r$i.stderr.log"
        $requestedTaskCount = if ([string]::IsNullOrWhiteSpace($TaskList)) { 51 } else { @($TaskList.Split(',') | Where-Object { -not [string]::IsNullOrWhiteSpace($_) }).Count }
        # In 'both' mode only skill-sensitive tasks are duplicated, but 2x is a safe upper bound.
        $maximumRuns = if ($SkillModes -eq 'both') { $requestedTaskCount * 2 } else { $requestedTaskCount }
        $suiteTimeout = [Math]::Max(300, ($maximumRuns * ($TimeoutSeconds + $EvaluatorTimeoutSeconds + 60)))
        $processResult = Invoke-PharoProcess -Vm $prepared.Vm -Image $prepared.Image -Script $SuiteStScript `
            -Environment $suiteEnvironment -Stdout $suiteStdout -Stderr $suiteStderr `
            -TimeoutSeconds $suiteTimeout -LiveStdout:($Verbosity -gt 0)

        if ($processResult.ExitCode -ne 0) {
            Show-ProcessDiagnostics -Stdout $suiteStdout -Stderr $suiteStderr
            throw "Benchmark suite Pharo process failed with exit code $($processResult.ExitCode). Logs: $suiteStdout ; $suiteStderr"
        }

        if (-not (Test-Path -LiteralPath $output)) {
            Show-ProcessDiagnostics -Stdout $suiteStdout -Stderr $suiteStderr
            throw "Benchmark suite Pharo process exited successfully but did not create $output. Logs: $suiteStdout ; $suiteStderr"
        }
        Show-SuiteSummary $output
        Prune-RunImages
    }
}

function Show-Status {
    $latest = Get-LatestSuiteResult
    if ($null -eq $latest) {
        Write-Host "No suite result found under $ResultsDirectory"
        return
    }
    Show-SuiteSummary $latest.FullName
    if (Test-Path -LiteralPath $EnvironmentRecordFile) {
        $environment = Get-Content -LiteralPath $EnvironmentRecordFile -Raw | ConvertFrom-Json
        Write-Host ''
        Write-Host "Configured model: $($environment.lmStudio.modelId)"
        Write-Host "Context: $($environment.lmStudio.pcaContextSize) ($($environment.lmStudio.contextSizeSource))"
        if ($null -ne $environment.lmStudio.maximumContextSize) { Write-Host "Maximum context: $($environment.lmStudio.maximumContextSize)" }
        Write-Host "Reasoning options: $(@($environment.lmStudio.reasoningOptions) -join ',')"
        Write-Host "Reasoning: $($environment.lmStudio.requestedReasoning)"
        Write-Host "Repository commit: $($environment.repositoryCommit)"
    }
}

# -----------------------------------------------------------------------------
# Main
# -----------------------------------------------------------------------------

if ($Repeat -lt 1) { throw '-Repeat must be at least 1.' }
if ($ContextSize -ne 0 -and $ContextSize -lt 4096) { throw '-ContextSize must be 0 (auto) or at least 4096.' }
if ($MaximumOutputTokens -lt 512) { throw '-MaximumOutputTokens is implausibly small.' }

switch ($Mode) {
    'Clean' {
        Remove-GeneratedWork
        Write-Host "Generated work removed. Preserved resources: $ResourcesDirectory"
        Write-Host "External evaluation repository preserved: $EvaluationRepository"
        break
    }
    'Models' {
        Show-LmStudioModels
        break
    }
    'Prepare' {
        $null = Prepare-Benchmark
        Write-Host "`nPreparation complete. No benchmark task was run." -ForegroundColor Green
        break
    }
    'Status' {
        Show-Status
        break
    }
    'Smoke' {
        $taskList = if ([string]::IsNullOrWhiteSpace($Tasks)) { $SmokeTasks } else { $Tasks }
        Invoke-BenchmarkSuite -TaskList $taskList -Label 'smoke'
        break
    }
    'Quick' {
        $taskList = if ([string]::IsNullOrWhiteSpace($Tasks)) { $QuickTasks } else { $Tasks }
        Invoke-BenchmarkSuite -TaskList $taskList -Label 'quick'
        break
    }
    'Task' {
        if ([string]::IsNullOrWhiteSpace($Tasks)) {
            throw "-Mode Task requires -Tasks, for example -Tasks 'navigation-007-cache-invalidation'."
        }
        Invoke-BenchmarkSuite -TaskList $Tasks -Label 'task'
        break
    }
    'Full' {
        if (-not [string]::IsNullOrWhiteSpace($Tasks)) {
            Write-Warn '-Mode Full ignores -Tasks. Use -Mode Task or Quick for a subset.'
        }
        Invoke-BenchmarkSuite -TaskList '' -Label 'full'
        break
    }
}
