function Write-Step([string]$Message) {
    if ($Verbosity -ge 1) { Write-Host "`n==> $Message" -ForegroundColor Cyan }
}

function Write-Info([string]$Message) {
    if ($Verbosity -ge 1) { Write-Host "    $Message" }
}

function Write-Warn([string]$Message) {
    Write-Warning $Message
}

function Ensure-Directory([string]$Path) {
    if (-not (Test-Path -LiteralPath $Path)) {
        New-Item -ItemType Directory -Force -Path $Path | Out-Null
    }
}

function Remove-GeneratedWork {
    if (Test-Path -LiteralPath $WorkDirectory) {
        Write-Step "Removing generated benchmark work tree: $WorkDirectory"
        Remove-Item -LiteralPath $WorkDirectory -Recurse -Force
    }
}

function Assert-Inputs {
    $missing = @()
    if (-not (Test-Path -LiteralPath $ResourcesDirectory -PathType Container)) { $missing += $ResourcesDirectory }
    if (-not (Test-Path -LiteralPath $VmArchive -PathType Leaf)) { $missing += $VmArchive }
    if (-not (Test-Path -LiteralPath $ImageArchive -PathType Leaf)) { $missing += $ImageArchive }
    if (-not (Test-Path -LiteralPath $Repository -PathType Container)) { $missing += $Repository }
    if (-not (Test-Path -LiteralPath $SuiteScript -PathType Leaf)) { $missing += $SuiteScript }
    if (-not (Test-Path -LiteralPath $SuiteStScript -PathType Leaf)) { $missing += $SuiteStScript }
    if (-not (Test-Path -LiteralPath $SupervisorScript -PathType Leaf)) { $missing += $SupervisorScript }
    if (-not (Test-Path -LiteralPath $BenchmarkPackage -PathType Container)) { $missing += $BenchmarkPackage }
    if (-not $NoEvaluation -and -not (Test-Path -LiteralPath $EvaluationRepository -PathType Container)) { $missing += $EvaluationRepository }
    if (-not $NoEvaluation -and -not (Test-Path -LiteralPath (Join-Path $EvaluationRepository 'src\PharoCodingAssistant-BenchmarkEvaluations') -PathType Container)) { $missing += (Join-Path $EvaluationRepository 'src\PharoCodingAssistant-BenchmarkEvaluations') }

    if ($missing.Count -gt 0) {
        throw "Required benchmark input(s) are missing:`n - $($missing -join "`n - ")"
    }

}

function Expand-ArchiveOnce([string]$Archive, [string]$Destination, [string]$MarkerName) {
    $marker = Join-Path $Destination $MarkerName
    if (Test-Path -LiteralPath $marker) { return }

    if (Test-Path -LiteralPath $Destination) {
        Remove-Item -LiteralPath $Destination -Recurse -Force
    }
    Ensure-Directory $Destination
    Write-Step "Extracting $(Split-Path -Leaf $Archive)"
    Expand-Archive -LiteralPath $Archive -DestinationPath $Destination -Force
    New-Item -ItemType File -Force -Path $marker | Out-Null
}

function Find-PharoVm {
    $preferred = @(Get-ChildItem -LiteralPath $VmDirectory -Recurse -File -Filter 'PharoConsole.exe')
    if ($preferred.Count -eq 0) {
        $preferred = @(Get-ChildItem -LiteralPath $VmDirectory -Recurse -File -Filter 'Pharo.exe')
    }
    if ($preferred.Count -eq 0) {
        throw "No PharoConsole.exe or Pharo.exe was found after extracting $VmArchive"
    }
    if ($preferred.Count -gt 1) {
        Write-Warn "Multiple Pharo executables found; using $($preferred[0].FullName)"
    }
    return $preferred[0].FullName
}

function Find-PharoImage {
    $images = @(Get-ChildItem -LiteralPath $ImageDirectory -Recurse -File -Filter '*.image' |
        Sort-Object -Property Name)
    if ($images.Count -eq 0) {
        throw "No .image file was found after extracting $ImageArchive"
    }

    # The resource archive is expected to contain one image. If that changes, prefer
    # the standard PharoNN...64bit-<hash>.image naming convention, then the newest file.
    if ($images.Count -gt 1) {
        $named = @($images | Where-Object { $_.Name -match '^Pharo.*64bit-.*\.image$' })
        if ($named.Count -eq 1) { return $named[0].FullName }
        $images = @($images | Sort-Object -Property LastWriteTimeUtc -Descending)
        Write-Warn "Multiple Pharo images found; using $($images[0].Name)"
    }
    return $images[0].FullName
}

function Invoke-PharoProcess {
    param(
        [Parameter(Mandatory=$true)][string]$Vm,
        [Parameter(Mandatory=$true)][string]$Image,
        [Parameter(Mandatory=$true)][string]$Script,
        [hashtable]$Environment = @{},
        [Parameter(Mandatory=$true)][string]$Stdout,
        [Parameter(Mandatory=$true)][string]$Stderr,
        [int]$TimeoutSeconds = 120,
        [switch]$LiveStdout
    )

    $stdoutParent = Split-Path -Parent $Stdout
    $stderrParent = Split-Path -Parent $Stderr
    if ($stdoutParent) { Ensure-Directory $stdoutParent }
    if ($stderrParent) { Ensure-Directory $stderrParent }

    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $psi.FileName = $Vm
    # Every benchmark VM process is explicitly headless.  Always redirect the
    # native streams and tee them ourselves: inherited console handles are not
    # reliable through the nested Windows suite -> system() -> PowerShell -> VM
    # process chain.
    $psi.Arguments = "--headless `"$Image`" st --quit `"$Script`""
    $psi.WorkingDirectory = Split-Path -Parent $Vm
    $psi.UseShellExecute = $false
    $psi.CreateNoWindow = $true
    $psi.RedirectStandardOutput = $true
    $psi.RedirectStandardError = $true

    foreach ($key in $Environment.Keys) {
        $value = $Environment[$key]
        if ($null -eq $value) {
            $psi.EnvironmentVariables.Remove([string]$key)
        } else {
            $psi.EnvironmentVariables[[string]$key] = [string]$value
        }
    }

    $process = New-Object System.Diagnostics.Process
    $process.StartInfo = $psi
    if (-not $process.Start()) {
        return [pscustomobject]@{ ExitCode = 125; TimedOut = $false; Arguments = $psi.Arguments }
    }

    $stdoutWriter = New-Object -TypeName System.IO.StreamWriter -ArgumentList $Stdout, $false
    $stderrWriter = New-Object -TypeName System.IO.StreamWriter -ArgumentList $Stderr, $false
    $stdoutWriter.AutoFlush = $true
    $stderrWriter.AutoFlush = $true

    $stdoutBuffer = New-Object 'char[]' 4096
    $stderrBuffer = New-Object 'char[]' 4096
    $stdoutTask = $process.StandardOutput.ReadAsync($stdoutBuffer, 0, $stdoutBuffer.Length)
    $stderrTask = $process.StandardError.ReadAsync($stderrBuffer, 0, $stderrBuffer.Length)
    $stdoutDone = $false
    $stderrDone = $false
    $timedOut = $false
    $deadline = [DateTime]::UtcNow.AddSeconds($TimeoutSeconds)

    try {
        while (-not ($process.HasExited -and $stdoutDone -and $stderrDone)) {
            $didWork = $false

            if (-not $stdoutDone -and $stdoutTask.IsCompleted) {
                $count = $stdoutTask.Result
                if ($count -le 0) {
                    $stdoutDone = $true
                } else {
                    $text = -join $stdoutBuffer[0..($count - 1)]
                    $stdoutWriter.Write($text)
                    $stdoutWriter.Flush()
                    if ($LiveStdout.IsPresent) { [Console]::Out.Write($text) }
                    $stdoutBuffer = New-Object 'char[]' 4096
                    $stdoutTask = $process.StandardOutput.ReadAsync($stdoutBuffer, 0, $stdoutBuffer.Length)
                }
                $didWork = $true
            }

            if (-not $stderrDone -and $stderrTask.IsCompleted) {
                $count = $stderrTask.Result
                if ($count -le 0) {
                    $stderrDone = $true
                } else {
                    $text = -join $stderrBuffer[0..($count - 1)]
                    $stderrWriter.Write($text)
                    $stderrWriter.Flush()
                    if ($LiveStdout.IsPresent) { [Console]::Error.Write($text) }
                    $stderrBuffer = New-Object 'char[]' 4096
                    $stderrTask = $process.StandardError.ReadAsync($stderrBuffer, 0, $stderrBuffer.Length)
                }
                $didWork = $true
            }

            if (-not $process.HasExited -and -not $timedOut -and [DateTime]::UtcNow -ge $deadline) {
                $timedOut = $true
                try { $process.Kill() } catch { }
            }

            if (-not $didWork) { Start-Sleep -Milliseconds 10 }
        }
        $process.WaitForExit()
    } finally {
        $stdoutWriter.Dispose()
        $stderrWriter.Dispose()
    }

    $exitCode = if ($timedOut) { 124 } else { $process.ExitCode }
    return [pscustomobject]@{ ExitCode = $exitCode; TimedOut = $timedOut; Arguments = $psi.Arguments }
}

function Show-ProcessDiagnostics([string]$Stdout, [string]$Stderr) {
    if (Test-Path -LiteralPath $Stdout) {
        $text = Get-Content -LiteralPath $Stdout -Raw -ErrorAction SilentlyContinue
        if (-not [string]::IsNullOrWhiteSpace($text)) {
            Write-Host "--- Pharo stdout ---" -ForegroundColor Yellow
            Write-Host $text.TrimEnd()
        }
    }
    if (Test-Path -LiteralPath $Stderr) {
        $text = Get-Content -LiteralPath $Stderr -Raw -ErrorAction SilentlyContinue
        if (-not [string]::IsNullOrWhiteSpace($text)) {
            Write-Host "--- Pharo stderr ---" -ForegroundColor Yellow
            Write-Host $text.TrimEnd()
        }
    }
}

function Test-PharoCommandLine([string]$Vm, [string]$Image) {
    Ensure-Directory $StateDirectory
    $probeScript = Join-Path $StateDirectory 'pharo-preflight.st'
    $marker = Join-Path $StateDirectory 'pharo-preflight.marker'
    $escapedMarker = $marker.Replace("'", "''")
    $probe = @"
| marker |
marker := '$escapedMarker' asFileReference.
marker parent ensureCreateDirectory.
marker writeStreamDo: [ :stream | stream nextPutAll: 'ok' ].
Stdio stdout nextPutAll: 'PCA-PHARO-PREFLIGHT-OK'; lf; flush.
Smalltalk snapshot: false andQuit: true.
"@
    [System.IO.File]::WriteAllText($probeScript, $probe, [System.Text.UTF8Encoding]::new($false))

    Remove-Item -LiteralPath $marker -Force -ErrorAction SilentlyContinue
    $stdout = Join-Path $StateDirectory 'pharo-preflight.stdout.log'
    $stderr = Join-Path $StateDirectory 'pharo-preflight.stderr.log'
    Write-Step 'Testing explicit headless Pharo command-line execution'
    $result = Invoke-PharoProcess -Vm $Vm -Image $Image -Script $probeScript -Stdout $stdout -Stderr $stderr -TimeoutSeconds 60
    if ($result.ExitCode -eq 0 -and (Test-Path -LiteralPath $marker -PathType Leaf)) {
        Write-Info 'Pharo .st execution works in explicit --headless mode.'
        [System.IO.File]::WriteAllText($PharoInvocationRecordFile, 'headless', [System.Text.UTF8Encoding]::new($false))
        return 'headless'
    }

    Show-ProcessDiagnostics -Stdout $stdout -Stderr $stderr
    throw "The extracted Pharo VM did not execute a .st file with explicit --headless. See $StateDirectory\pharo-preflight*.log"
}

function Get-ApiUrls {
    $root = $LmStudioUrl.TrimEnd('/')
    if ($root -match '/v1$') {
        $serverRoot = $root.Substring(0, $root.Length - 3).TrimEnd('/')
        $v1 = $root
    } else {
        $serverRoot = $root
        $v1 = "$root/v1"
    }
    return [pscustomobject]@{
        ServerRoot = $serverRoot
        V1 = $v1
        Models = "$v1/models"
        NativeModels = "$serverRoot/api/v1/models"
        Chat = "$v1/chat/completions"
    }
}

function Get-LmStudioModels {
    $urls = Get-ApiUrls
    Write-Step "Querying LM Studio: $($urls.Models)"
    try {
        $response = Invoke-RestMethod -Method Get -Uri $urls.Models -TimeoutSec 15
    } catch {
        throw "LM Studio is not reachable at $($urls.Models). Start the LM Studio API server and load the model. $($_.Exception.Message)"
    }

    if ($null -eq $response.data) {
        throw "LM Studio /v1/models response has no 'data' array."
    }

    Ensure-Directory $StateDirectory
    $json = $response | ConvertTo-Json -Depth 20
    [System.IO.File]::WriteAllText($ModelListRecordFile, $json, [System.Text.UTF8Encoding]::new($false))
    return @($response.data)
}


function Get-LmStudioNativeModels {
    $urls = Get-ApiUrls
    try {
        $response = Invoke-RestMethod -Method Get -Uri $urls.NativeModels -TimeoutSec 15
    } catch {
        Write-Warn "LM Studio native model metadata is unavailable at $($urls.NativeModels). Context/reasoning auto-detection may be limited. $($_.Exception.Message)"
        return @()
    }

    if ($null -eq $response.models) {
        Write-Warn "LM Studio $($urls.NativeModels) response has no 'models' array."
        return @()
    }

    Ensure-Directory $StateDirectory
    $json = $response | ConvertTo-Json -Depth 30
    [System.IO.File]::WriteAllText($NativeModelListRecordFile, $json, [System.Text.UTF8Encoding]::new($false))
    return @($response.models)
}

function Find-LmStudioNativeModelMatch([object[]]$NativeModels, [string]$SelectedModelId) {
    # A custom LM Studio identifier can be the loaded-instance id while the underlying
    # native model key/variant has a completely different name. Match that first.
    foreach ($model in $NativeModels) {
        foreach ($instance in @($model.loaded_instances)) {
            if ($null -ne $instance -and [string]$instance.id -eq $SelectedModelId) {
                return [pscustomobject]@{ Model = $model; Instance = $instance; Match = 'loaded-instance-id' }
            }
        }
    }

    foreach ($model in $NativeModels) {
        if ([string]$model.key -eq $SelectedModelId) {
            $instance = @($model.loaded_instances) | Select-Object -First 1
            return [pscustomobject]@{ Model = $model; Instance = $instance; Match = 'model-key' }
        }
        if (($model.PSObject.Properties.Name -contains 'selected_variant') -and [string]$model.selected_variant -eq $SelectedModelId) {
            $instance = @($model.loaded_instances) | Select-Object -First 1
            return [pscustomobject]@{ Model = $model; Instance = $instance; Match = 'selected-variant' }
        }
        foreach ($variant in @($model.variants)) {
            if ([string]$variant -eq $SelectedModelId) {
                $instance = @($model.loaded_instances) | Select-Object -First 1
                return [pscustomobject]@{ Model = $model; Instance = $instance; Match = 'variant' }
            }
        }
    }
    return $null
}

function Resolve-LmStudioModelMetadata(
    [object[]]$OpenAiModels,
    [object[]]$NativeModels,
    [string]$SelectedModelId
) {
    $openAi = $OpenAiModels | Where-Object { [string]$_.id -eq $SelectedModelId } | Select-Object -First 1
    $match = Find-LmStudioNativeModelMatch -NativeModels $NativeModels -SelectedModelId $SelectedModelId

    $nativeModel = $null
    $instance = $null
    $maximumContext = $null
    $loadedContext = $null
    $contextSource = $null
    $metadataSource = $null
    $reasoningOptions = @()
    $defaultReasoning = $null
    $supportsReasoning = $false
    $supportsTools = $true
    $supportsImages = $false

    if ($null -ne $match) {
        $nativeModel = $match.Model
        $instance = $match.Instance
        $metadataSource = 'lmstudio-native-v1'

        if (($nativeModel.PSObject.Properties.Name -contains 'max_context_length') -and $null -ne $nativeModel.max_context_length) {
            $maximumContext = [int64]$nativeModel.max_context_length
        }
        if ($null -ne $instance -and $null -ne $instance.config -and
            ($instance.config.PSObject.Properties.Name -contains 'context_length') -and
            $null -ne $instance.config.context_length) {
            $loadedContext = [int64]$instance.config.context_length
        }

        if ($null -ne $nativeModel.capabilities) {
            if ($nativeModel.capabilities.PSObject.Properties.Name -contains 'trained_for_tool_use') {
                $supportsTools = [bool]$nativeModel.capabilities.trained_for_tool_use
            }
            if ($nativeModel.capabilities.PSObject.Properties.Name -contains 'vision') {
                $supportsImages = [bool]$nativeModel.capabilities.vision
            }
            if (($nativeModel.capabilities.PSObject.Properties.Name -contains 'reasoning') -and $null -ne $nativeModel.capabilities.reasoning) {
                $reasoningOptions = @($nativeModel.capabilities.reasoning.allowed_options | ForEach-Object { [string]$_ })
                if ($nativeModel.capabilities.reasoning.PSObject.Properties.Name -contains 'default') {
                    $defaultReasoning = [string]$nativeModel.capabilities.reasoning.default
                }
                $supportsReasoning = $reasoningOptions.Count -gt 0
            }
        }
    }

    if ($ContextSize -gt 0) {
        $effectiveContext = [int64]$ContextSize
        $contextSource = 'manual-override'
    } elseif ($null -ne $loadedContext -and $loadedContext -gt 0) {
        $effectiveContext = [int64]$loadedContext
        $contextSource = 'loaded-instance'
    } elseif ($null -ne $maximumContext -and $maximumContext -gt 0) {
        $effectiveContext = [int64]$maximumContext
        $contextSource = 'model-maximum'
        Write-Warn "No loaded-instance context was found for '$SelectedModelId'; using the model maximum $effectiveContext. For reproducible benchmarking, load the model explicitly in LM Studio first."
    } else {
        $legacyContext = $null
        if ($null -ne $openAi) {
            if (($openAi.PSObject.Properties.Name -contains 'context_length') -and $null -ne $openAi.context_length) {
                $legacyContext = [int64]$openAi.context_length
            } elseif (($openAi.PSObject.Properties.Name -contains 'max_context_length') -and $null -ne $openAi.max_context_length) {
                $legacyContext = [int64]$openAi.max_context_length
            }
        }
        if ($null -eq $legacyContext -or $legacyContext -le 0) {
            throw "Could not determine the context window for '$SelectedModelId'. Load the model in a current LM Studio version or pass -ContextSize explicitly."
        }
        $effectiveContext = $legacyContext
        $contextSource = 'openai-model-list'
        $metadataSource = 'openai-model-list'
    }

    $requestedReasoning = $Reasoning.Trim().ToLowerInvariant()
    if ([string]::IsNullOrWhiteSpace($requestedReasoning) -or $requestedReasoning -eq 'auto') {
        $requestedReasoning = 'provider-default'
    }
    if ($requestedReasoning -eq 'none' -and $reasoningOptions -contains 'off') {
        $requestedReasoning = 'off'
    }

    $effectiveReasoning = $null
    if ($requestedReasoning -ne 'provider-default') {
        if (-not $supportsReasoning) {
            throw "Model '$SelectedModelId' does not advertise configurable reasoning. Use -Reasoning provider-default."
        }
        if (-not ($reasoningOptions -contains $requestedReasoning)) {
            throw "Reasoning '$Reasoning' is not supported by '$SelectedModelId'. Allowed values: provider-default,$($reasoningOptions -join ',')"
        }
        $effectiveReasoning = $requestedReasoning
    }

    return [pscustomobject]@{
        OpenAiDescriptor = $openAi
        NativeModel = $nativeModel
        LoadedInstance = $instance
        NativeMatch = $(if ($null -eq $match) { $null } else { $match.Match })
        ContextSize = [int64]$effectiveContext
        MaximumContextSize = $maximumContext
        ContextSizeSource = $contextSource
        MetadataSource = $metadataSource
        ReasoningOptions = @($reasoningOptions)
        DefaultReasoning = $defaultReasoning
        RequestedReasoning = $requestedReasoning
        EffectiveReasoning = $effectiveReasoning
        SupportsReasoning = [bool]$supportsReasoning
        SupportsTools = [bool]$supportsTools
        SupportsImages = [bool]$supportsImages
    }
}

function Show-LmStudioModels {
    $models = @(Get-LmStudioModels)
    $nativeModels = @(Get-LmStudioNativeModels)
    if ($models.Count -eq 0) {
        Write-Host 'LM Studio returned no models.'
        return
    }
    Write-Host ''
    foreach ($model in $models) {
        $id = [string]$model.id
        $match = Find-LmStudioNativeModelMatch -NativeModels $nativeModels -SelectedModelId $id
        $parts = @()
        if ($null -ne $match) {
            $native = $match.Model
            $instance = $match.Instance
            if ($null -ne $instance -and $null -ne $instance.config -and $null -ne $instance.config.context_length) {
                $parts += "context=$($instance.config.context_length) loaded"
            } elseif ($null -ne $native.max_context_length) {
                $parts += "context<=$($native.max_context_length)"
            }
            if ($null -ne $native.capabilities -and $null -ne $native.capabilities.reasoning) {
                $options = @($native.capabilities.reasoning.allowed_options | ForEach-Object { [string]$_ })
                $default = [string]$native.capabilities.reasoning.default
                if ($options.Count -gt 0) { $parts += "reasoning=$($options -join '/') default=$default" }
            } else {
                $parts += 'reasoning=not-advertised'
            }
        }
        $suffix = if ($parts.Count -gt 0) { '  [' + ($parts -join '; ') + ']' } else { '' }
        Write-Host "  $id$suffix"
    }
}

function Select-LmStudioModel([object[]]$Models) {
    $ids = @($Models | ForEach-Object { [string]$_.id })
    if ($ids.Count -eq 0) { throw 'LM Studio returned no model identifiers.' }

    if (-not [string]::IsNullOrWhiteSpace($ModelId)) {
        $exact = @($ids | Where-Object { $_ -eq $ModelId })
        if ($exact.Count -ne 1) {
            throw "Requested model '$ModelId' was not returned by LM Studio. Available models:`n - $($ids -join "`n - ")"
        }
        return $exact[0]
    }

    $matches = @($ids | Where-Object { $_ -like $ModelPattern })
    if ($matches.Count -eq 0) {
        # Be tolerant of punctuation differences such as Qwen3_8 / Qwen3.8 / Qwen3-8.
        $wanted = ($ModelPattern -replace '[^A-Za-z0-9]', '').ToLowerInvariant().Replace('*','')
        $matches = @($ids | Where-Object {
            (($_ -replace '[^A-Za-z0-9]', '').ToLowerInvariant()).Contains($wanted)
        })
    }

    if ($matches.Count -eq 0) {
        throw "No LM Studio model matches '$ModelPattern'. Use -Mode Models to list models or pass -ModelId explicitly.`nAvailable models:`n - $($ids -join "`n - ")"
    }
    if ($matches.Count -gt 1) {
        throw "More than one LM Studio model matches '$ModelPattern'. Pass -ModelId explicitly:`n - $($matches -join "`n - ")"
    }
    return $matches[0]
}

